// 为「泄露源码中被裁剪掉的模块」生成磁盘 stub，使 src/ 可被 Bun 直接运行/调试。
// 与 devkit/build.ts 的 auto-stub 语义一致（Proxy 兜底），但落成真实文件：
// Bun 运行时插件无法拦截静态 ESM import，只能靠文件存在。
//
// 用法:
//   bun devkit/debug-stubs.ts           生成/更新 stub，并维护 .gitignore 管理块
//   bun devkit/debug-stubs.ts --clean   删除所有生成的 stub 与 .gitignore 管理块
//
// 安全：只写不存在、或以 stub 标记开头的文件，绝不覆盖真实源码。
import { existsSync, mkdirSync, readFileSync, readdirSync, rmdirSync, writeFileSync, rmSync } from 'node:fs'
import path from 'node:path'

const ROOT = path.join(import.meta.dir, '..')
const MARKER = '/* __devkit_debug_stub__ */'
const GI_START = '# >>> devkit debug stubs (auto-generated by devkit/debug-stubs.ts) >>>'
const GI_END = '# <<< devkit debug stubs <<<'
const NODE_BUILTINS = new Set([
  'assert', 'async_hooks', 'buffer', 'child_process', 'cluster', 'crypto', 'dgram',
  'diagnostics_channel', 'dns', 'events', 'fs', 'http', 'http2', 'https', 'inspector',
  'module', 'net', 'os', 'path', 'perf_hooks', 'process', 'punycode', 'querystring',
  'readline', 'repl', 'stream', 'string_decoder', 'sys', 'timers', 'tls', 'trace_events',
  'tty', 'url', 'util', 'v8', 'vm', 'wasi', 'worker_threads', 'zlib',
])

const PROXY_BODY = `const _ = new Proxy(function () {}, {
  get: (t, p) => {
    if (typeof p === 'symbol') {
      if (p === Symbol.toPrimitive) return () => '';
      if (p === Symbol.iterator) return function* () {};
      return undefined;
    }
    if (p === 'then' || p === 'toJSON') return undefined;
    if (p === 'valueOf' || p === 'toString') return () => '';
    return _;
  },
  apply: () => _,
  construct: () => _,
  has: () => true,
});`

function existsWithExt(base: string, ignoreStubs = false): boolean {
  const ok = (p: string) => existsSync(p) && !(ignoreStubs && isStubFile(p))
  for (const e of ['', '.ts', '.tsx', '.js', '.jsx', '.mjs', '.cjs']) {
    if (ok(base + e)) return true
    for (const idx of ['index.ts', 'index.tsx', 'index.js']) {
      if (ok(path.join(base + e, idx))) return true
    }
  }
  return false
}

// specifier -> 绝对目标路径（保留 specifier 的扩展名）
function resolveTarget(spec: string, importer: string): string | null {
  if (spec.startsWith('src/')) return path.join(ROOT, spec)
  if (spec.startsWith('./') || spec.startsWith('../')) return path.resolve(path.dirname(importer), spec)
  return null
}

interface ImportInfo { named: Set<string>; defaultImport: boolean }

async function scanMissing(): Promise<Map<string, ImportInfo>> {
  const missing = new Map<string, ImportInfo>()
  const specRe = /(?:import\s+(?:([A-Za-z_$][\w$]*)\s*,\s*)?(?:\{([^}]*)\}|\*\s+as\s+[A-Za-z_$][\w$]*|[A-Za-z_$][\w$]*)\s+from\s+|import\s*\(\s*|require\s*\(\s*|export\s+(?:\{([^}]*)\}|\*)\s+from\s+)['"]([^'"]+)['"]|import\s+['"]([^'"]+)['"]/g
  const glob = new Bun.Glob('src/**/*.{ts,tsx,js,jsx}')
  for await (const file of glob.scan()) {
    const abs = path.join(ROOT, file)
    let src: string
    try { src = await Bun.file(abs).text() } catch { continue }
    for (const m of src.matchAll(specRe)) {
      const spec = m[4] ?? m[5]!
      if (!spec.startsWith('.') && !spec.startsWith('src/')) continue
      const noExt = spec.replace(/\.(js|jsx|mjs|cjs|d\.ts|ts|tsx|md|txt|json)$/, '')
      const base = resolveTarget(noExt, abs)!
      if (existsWithExt(base, true)) continue
      const target = resolveTarget(spec, abs)!
      let info = missing.get(target)
      if (!info) { info = { named: new Set(), defaultImport: false }; missing.set(target, info) }
      if (m[1]) info.defaultImport = true
      if (m[3] === '') info.defaultImport = true // export * from
      for (const rawNames of [m[2], m[3]]) {
        if (!rawNames) continue
        for (let part of rawNames.split(',')) {
          part = part.trim()
          if (!part || part === 'type' || part.startsWith('type ')) continue
          const asM = part.match(/^([A-Za-z_$][\w$]*)\s+as\s+[A-Za-z_$][\w$]*$/)
          info.named.add(asM ? asM[1]! : part.replace(/^type\s+/, ''))
        }
      }
    }
  }
  return missing
}

function isStubFile(abs: string): boolean {
  try { return readFileSync(abs, 'utf8').startsWith(MARKER) } catch { return false }
}

function gitignoreUpdate(paths: string[]) {
  const gi = path.join(ROOT, '.gitignore')
  let content = existsSync(gi) ? readFileSync(gi, 'utf8') : ''
  const startIdx = content.indexOf(GI_START)
  const endIdx = content.indexOf(GI_END)
  if (startIdx !== -1 && endIdx !== -1) {
    content = content.slice(0, startIdx) + content.slice(endIdx + GI_END.length + 1)
  }
  if (paths.length > 0) {
    const block = [GI_START, ...paths.sort(), GI_END].join('\n') + '\n'
    content = content.replace(/\n*$/, '\n') + block
  }
  writeFileSync(gi, content)
}

function removeEmptyDirs(dir: string) {
  if (!dir.startsWith(path.join(ROOT, 'src'))) return
  try {
    while (dir !== path.join(ROOT, 'src') && readdirSync(dir).length === 0) {
      rmdirSync(dir)
      dir = path.dirname(dir)
    }
  } catch {}
}

async function clean() {
  const gi = path.join(ROOT, '.gitignore')
  const content = existsSync(gi) ? readFileSync(gi, 'utf8') : ''
  const startIdx = content.indexOf(GI_START)
  const endIdx = content.indexOf(GI_END)
  if (startIdx === -1 || endIdx === -1) { console.log('没有需要清理的 stub 管理块'); return }
  const paths = content.slice(startIdx + GI_START.length + 1, endIdx).split('\n').map(s => s.trim()).filter(Boolean)
  for (const rel of paths) {
    const abs = path.join(ROOT, rel)
    if (existsSync(abs) && isStubFile(abs)) {
      rmSync(abs)
      removeEmptyDirs(path.dirname(abs))
    }
  }
  gitignoreUpdate([])
  console.log(`🧹 cleaned ${paths.length} debug stubs`)
}

async function generate() {
  const missing = await scanMissing()
  let written = 0, kept = 0
  const stubPaths: string[] = []
  for (const [target, info] of [...missing].sort(([a], [b]) => a.localeCompare(b))) {
    const rel = path.relative(ROOT, target)
    const ext = path.extname(target)
    stubPaths.push(rel)
    if (existsSync(target)) {
      if (isStubFile(target)) { kept++; continue }
      console.warn(`⚠️  跳过已存在的真实文件: ${rel}`)
      stubPaths.pop()
      continue
    }
    mkdirSync(path.dirname(target), { recursive: true })
    if (ext === '.md' || ext === '.txt') {
      writeFileSync(target, `${MARKER}\n原文件未包含在泄露源码中，此文件为调试占位。\n`)
    } else {
      const lines = [MARKER, PROXY_BODY]
      if (info.defaultImport || info.named.size === 0) lines.push('export default _;')
      for (const n of info.named) lines.push(`export { _ as ${n} };`)
      writeFileSync(target, lines.join('\n') + '\n')
    }
    written++
  }
  gitignoreUpdate(stubPaths)
  console.log(`✅ ${written} stubs written, ${kept} up-to-date, total ${stubPaths.length} tracked in .gitignore`)
}

if (process.argv.includes('--clean')) await clean()
else await generate()
